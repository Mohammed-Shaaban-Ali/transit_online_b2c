const ALPHA3_TO_ALPHA2 = Object.fromEntries(
  Object.entries(ALPHA2_TO_ALPHA3).map(([alpha2, alpha3]) => [alpha3, alpha2]),
);

export function normalizeCountryCodeToAlpha2(code: string): string {
  const trimmed = code.trim().toUpperCase();
  if (!trimmed) return "";

  if (trimmed.length === 2) {
    return trimmed;
  }

  if (trimmed.length === 3) {
    return ALPHA3_TO_ALPHA2[trimmed] || trimmed;
  }

  return trimmed;
}
